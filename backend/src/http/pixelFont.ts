export const PIXEL_ROWS = 7;

/** Lit cells of a string, one blank column between glyphs */
export function pixelCells(text: string): { width: number; cells: Array<{ x: number; y: number }> } {
  const cells: Array<{ x: number; y: number }> = [];
  let x = 0;
  const chars = [...text];
  chars.forEach((ch, i) => {
    const g = RAW[ch] ?? RAW[ch.toUpperCase()] ?? RAW["?"];
    const w = g[0].length;
    g.forEach((row, y) => {
      for (let c = 0; c < w; c++) if (row[c] === "#") cells.push({ x: x + c, y });
    });
    x += w + (i < chars.length - 1 ? 1 : 0);
  });
  return { width: x, cells };
}
