export const ROWS = 7;

export interface Cell {
  x: number;
  y: number;
  /** Lit in this text (always true from layout(); display grids include unlit cells) */
  on: boolean;
}

export interface PixelLayout {
  width: number;
  cells: Cell[];
}

function glyph(ch: string): string[] {
  return RAW[ch] ?? RAW[ch.toUpperCase()] ?? RAW["?"];
}

/** Lay out a string with one blank column between glyphs. */
export function layout(text: string, tracking = 1): PixelLayout {
  const cells: Cell[] = [];
  let x = 0;
  const chars = [...text];
  chars.forEach((ch, i) => {
    const g = glyph(ch);
    const w = g[0].length;
    g.forEach((row, y) => {
      for (let c = 0; c < w; c++) if (row[c] === "#") cells.push({ x: x + c, y, on: true });
    });
    x += w + (i < chars.length - 1 ? tracking : 0);
  });
  return { width: x, cells };
}

/** Every cell of the text's bounding box, lit or not (for LED style displays). */
export function grid(text: string, tracking = 1): PixelLayout {
  const lit = layout(text, tracking);
  const on = new Set(lit.cells.map((c) => `${c.x},${c.y}`));
  const cells: Cell[] = [];
  for (let y = 0; y < ROWS; y++) for (let x = 0; x < lit.width; x++) cells.push({ x, y, on: on.has(`${x},${y}`) });
  return { width: lit.width, cells };
}
